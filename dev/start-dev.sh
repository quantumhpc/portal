#!/usr/bin/env bash
# ===========================================================================
# QuantumHPC Portal – Local Dev Environment Setup
# ---------------------------------------------------------------------------
# Modes:
#   --mode sqlite  (default) — sqlite db, local mock binaries (no docker)
#   --mode ssh               — sqlite db, mock cluster in a docker container
#                              reached over ssh on localhost:2222
#   --mode mongo             — MongoDB container, local mock binaries
#
# Usage:
#   ./dev/start-dev.sh
#   ./dev/start-dev.sh --mode ssh
#   ./dev/start-dev.sh --mode mongo
# ===========================================================================
set -euo pipefail

MODE="sqlite"
while [ $# -gt 0 ]; do
  case "$1" in
    --mode)   MODE="$2"; shift 2 ;;
    --mode=*) MODE="${1#--mode=}"; shift ;;
    -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "Unknown arg: $1" >&2; exit 1 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
MOCK_DIR="$SCRIPT_DIR/slurm-mock"
KEYS_DIR="$SCRIPT_DIR/keys"

CONTAINER_NAME="qhpc-mongo"
MONGO_PORT=27017
MONGO_DB="quanta"
JOBS_DIR="/tmp/qhpc-dev-jobs"
HOME_DIR="/tmp/qhpc-dev-home"

CURRENT_USER=$(id -un)
ADMIN_USER="${ADMIN_USER:-$CURRENT_USER}"

echo "==> Mode: $MODE"
command -v node >/dev/null 2>&1 || { echo "ERROR: node not found"; exit 1; }
if [ "$MODE" = "mongo" ] || [ "$MODE" = "ssh" ]; then
  command -v docker >/dev/null 2>&1 || { echo "ERROR: docker not found"; exit 1; }
fi

chmod +x "$MOCK_DIR"/* "$SCRIPT_DIR/pbs-mock"/* 2>/dev/null || true
mkdir -p "$JOBS_DIR" "$HOME_DIR/jobs"

ENV_FILE="$PROJECT_DIR/.env.local"

# Site config is git-ignored; seed it from the dev template on first run.
if [ ! -f "$PROJECT_DIR/config/config.json" ]; then
  cp "$PROJECT_DIR/config/config.dev.json" "$PROJECT_DIR/config/config.json"
  echo "==> Created config/config.json from config/config.dev.json"
fi

# ---------------------------------------------------------------------------
case "$MODE" in

  sqlite)
    echo "==> Seeding SQLite store..."
    ADMIN_USER="$ADMIN_USER" node "$SCRIPT_DIR/seed.mjs"

    cat > "$ENV_FILE" <<EOF
# QuantumHPC Dev Environment – generated by dev/start-dev.sh (sqlite mode)
DB_DRIVER=sqlite
SQLITE_FILE=$PROJECT_DIR/dev/qhpc.sqlite
NEXTAUTH_SECRET=qhpc-dev-secret-do-not-use-in-production
NEXTAUTH_URL=http://localhost:3000
HPC_MANAGER=slurm
# Dev only: accept any password for an existing OS user
USE_PAM=false
ADMIN_USERS=$ADMIN_USER
EOF
    ;;

  ssh)
    echo "==> Generating SSH key for hpc-mock..."
    mkdir -p "$KEYS_DIR"
    if [ ! -f "$KEYS_DIR/id_rsa" ]; then
      ssh-keygen -t ed25519 -N "" -C "qhpc-mock-dev" -f "$KEYS_DIR/id_rsa" >/dev/null
    fi
    cp "$KEYS_DIR/id_rsa.pub" "$KEYS_DIR/authorized_keys"
    chmod 600 "$KEYS_DIR/id_rsa" "$KEYS_DIR/authorized_keys"

    echo "==> Building & starting hpc-mock container..."
    (cd "$PROJECT_DIR" && docker compose -f docker-compose.dev.yml up -d --build hpc-mock)

    echo -n "    Waiting for sshd on localhost:2222"
    for i in $(seq 1 30); do
      if (echo > /dev/tcp/localhost/2222) >/dev/null 2>&1; then
        echo " OK"; break
      fi
      echo -n "."; sleep 1
      if [ "$i" -eq 30 ]; then echo ""; echo "ERROR: sshd did not start"; exit 1; fi
    done

    echo "==> Seeding SQLite store with ssh-mock user config..."
    SSH_MOCK_KEY="$KEYS_DIR/id_rsa" SSH_MOCK_USER="hpcuser" \
    SSH_MOCK_BIN="/opt/qhpc-mock/slurm-mock" \
    SSH_MOCK_OPTS="-o Port=2222 -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR" \
    ADMIN_USER="$ADMIN_USER" node "$SCRIPT_DIR/seed.mjs"

    cat > "$ENV_FILE" <<EOF
# QuantumHPC Dev Environment – generated by dev/start-dev.sh (ssh mode)
DB_DRIVER=sqlite
SQLITE_FILE=$PROJECT_DIR/dev/qhpc.sqlite
NEXTAUTH_SECRET=qhpc-dev-secret-do-not-use-in-production
NEXTAUTH_URL=http://localhost:3000
HPC_MANAGER=slurm
# Dev only: accept any password for an existing OS user
USE_PAM=false
ADMIN_USERS=$ADMIN_USER
EOF
    ;;

  mongo)
    echo "==> Starting MongoDB container '$CONTAINER_NAME'..."
    if docker ps -a --format '{{.Names}}' | grep -q "^${CONTAINER_NAME}$"; then
      docker rm -f "$CONTAINER_NAME" >/dev/null
    fi

    docker run -d \
      --name "$CONTAINER_NAME" \
      -p "${MONGO_PORT}:27017" \
      -e MONGO_INITDB_DATABASE="$MONGO_DB" \
      mongo:7 >/dev/null

    echo -n "    Waiting for MongoDB"
    for i in $(seq 1 30); do
      if docker exec "$CONTAINER_NAME" mongosh --quiet --eval "db.adminCommand('ping')" >/dev/null 2>&1; then
        echo " OK"; break
      fi
      echo -n "."; sleep 1
      if [ "$i" -eq 30 ]; then echo ""; echo "ERROR: MongoDB did not start"; exit 1; fi
    done

    docker exec "$CONTAINER_NAME" mongosh --quiet "$MONGO_DB" --eval "
db.users.deleteMany({ username: '${ADMIN_USER}' });
db.users.insertOne({
  username:    '${ADMIN_USER}',
  displayName: '${ADMIN_USER}',
  admin:       { isAdmin: true, active: true },
  properties:  { version: '0.0.0-dev' },
});
print('Admin user created: ${ADMIN_USER}');
"

    cat > "$ENV_FILE" <<EOF
# QuantumHPC Dev Environment – generated by dev/start-dev.sh (mongo mode)
DB_DRIVER=mongo
MONGODB_HOST=localhost
MONGODB_PORT=27017
MONGODB_DATABASE=${MONGO_DB}
NEXTAUTH_SECRET=qhpc-dev-secret-do-not-use-in-production
NEXTAUTH_URL=http://localhost:3000
HPC_MANAGER=slurm
# Dev only: accept any password for an existing OS user
USE_PAM=false
ADMIN_USERS=$ADMIN_USER
EOF
    ;;

  *)
    echo "Unknown mode: $MODE (expected sqlite|ssh|mongo)" >&2
    exit 1 ;;
esac

echo "    Written: $ENV_FILE"

cat <<EOF

=== Setup complete! ==========================================

  Mode:      $MODE
  Login:     http://localhost:3000/login
  Username:  $ADMIN_USER  (OS credentials — PAM auth, no DB password)

  Job working dir:  $JOBS_DIR
  User home dir:    $HOME_DIR

  Start the app:  npm run dev
EOF

case "$MODE" in
  ssh)   echo "  Stop hpc-mock:  docker compose -f docker-compose.dev.yml down" ;;
  mongo) echo "  Stop MongoDB:   docker rm -f $CONTAINER_NAME" ;;
esac
echo "=============================================================="
